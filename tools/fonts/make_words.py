# 갈무리 글꼴로 제목 글자를 픽셀 지도로 뽑아 pixelfx 소스에서 쓰게 함
# 저장소 폴더에서 python tools/fonts/make_words.py 로 실행하면 tools/pixelfx/moonkeeper/_words.js 가 생김
import json
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(__file__)
# 게임 글꼴과 같은 파일을 씀
FONT = os.path.join(HERE, '..', '..', 'res', 'fonts', 'Galmuri11-Bold.ttf')
SIZE = 12
# 키웠을 때 글자 테두리끼리 붙지 않게 글자 사이를 한 칸씩 더 띄움
TRACK = 1
OUT = os.path.join(HERE, '..', 'pixelfx', 'moonkeeper', '_words.js')
WORDS = ['달지기', '지구를 지켰다', '지구가 무너졌다', '보스 등장'] + ['웨이브 %d' % n for n in range(1, 10)]


def mask(text, font):
    # 안티에일리어싱 없이 점 하나하나 그대로
    im = Image.new('L', (SIZE * 2 * len(text) + 8, SIZE + 6), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = '1'
    d.text((2, 1), text, font=font, fill=255)
    return im


def word(text, font):
    whole = mask(text, font)
    top, bottom = None, None
    box = whole.getbbox()
    top, bottom = box[1], box[3]
    chars = []
    for i, ch in enumerate(text):
        if ch == ' ':
            continue
        # 글자 하나씩 따로 움직이게 앞 글자까지의 폭으로 자리를 나눔
        x0 = 2 + round(font.getlength(text[:i]))
        x1 = 2 + round(font.getlength(text[:i + 1]))
        part = whole.crop((x0, top, x1, bottom))
        rows = [''.join('#' if part.getpixel((x, y)) else '.' for x in range(part.width)) for y in range(part.height)]
        chars.append({'ch': ch, 'x': x0 - box[0] + i * TRACK, 'rows': rows})
    return {'w': box[2] - box[0] + (len(text) - 1) * TRACK, 'h': bottom - top, 'chars': chars}


font = ImageFont.truetype(FONT, SIZE)
data = {w: word(w, font) for w in WORDS}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/fonts/make_words.py from Galmuri11 Bold 12px, SIL Open Font License. Do not edit by hand.\n')
    f.write('export const WORDS = ' + json.dumps(data, ensure_ascii=False) + ';\n')
print('words', len(data), 'sizes', {k: (v['w'], v['h']) for k, v in data.items() if not k.startswith('웨이브 ') or k.endswith('1')})
